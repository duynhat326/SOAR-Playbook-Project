class SupabaseIncidentRepository:
    """Supabase/Postgres-backed persistence for workflow executions and async remediation jobs."""

    def __init__(self, db_url: Optional[str | Path] = None) -> None:
        self.db_url = resolve_database_url(db_url, preferred_env="SOAR_DATABASE_URL")
        self.db_path = self.db_url
        self._db = PostgresDatabase(self.db_url, _INCIDENT_SCHEMA)

    def save_workflow_result(self, result: "WorkflowResult") -> int:
        alert = result.alert
        enriched = result.enriched_alert
        response = result.response
        correlation_trace = response.correlation_trace
        workspace = normalize_workspace(result.workspace)
        timestamp = self._utc_now()
        incident_status = self._derive_incident_status(response.action_results)
        incident_key = str(correlation_trace.incident_key or f"incident-{alert.alert_id}")
        latest_alert_id = str(alert.alert_id)

        with self._db.connect() as conn:
            conn.execute(
                """
                INSERT INTO alerts (
                    alert_id, workspace, hostname, username, process_name, file_path, file_hash,
                    parent_process, command_line, destination_ip, severity,
                    detection_name, received_at, raw_json, created_at, updated_at
                ) VALUES (
                    %(alert_id)s, %(workspace)s, %(hostname)s, %(username)s, %(process_name)s, %(file_path)s, %(file_hash)s,
                    %(parent_process)s, %(command_line)s, %(destination_ip)s, %(severity)s,
                    %(detection_name)s, %(received_at)s, %(raw_json)s, %(created_at)s, %(updated_at)s
                )
                ON CONFLICT (alert_id) DO UPDATE SET
                    workspace = EXCLUDED.workspace,
                    hostname = EXCLUDED.hostname,
                    username = EXCLUDED.username,
                    process_name = EXCLUDED.process_name,
                    file_path = EXCLUDED.file_path,
                    file_hash = EXCLUDED.file_hash,
                    parent_process = EXCLUDED.parent_process,
                    command_line = EXCLUDED.command_line,
                    destination_ip = EXCLUDED.destination_ip,
                    severity = EXCLUDED.severity,
                    detection_name = EXCLUDED.detection_name,
                    received_at = EXCLUDED.received_at,
                    raw_json = EXCLUDED.raw_json,
                    updated_at = EXCLUDED.updated_at
                """,
                {
                    "alert_id": alert.alert_id,
                    "workspace": workspace,
                    "hostname": alert.hostname,
                    "username": alert.username,
                    "process_name": alert.process_name,
                    "file_path": alert.file_path,
                    "file_hash": alert.file_hash,
                    "parent_process": alert.parent_process,
                    "command_line": alert.command_line,
                    "destination_ip": alert.destination_ip,
                    "severity": alert.severity.value,
                    "detection_name": alert.detection_name,
                    "received_at": alert.received_at,
                    "raw_json": Jsonb(alert.model_dump(mode="json")),
                    "created_at": timestamp,
                    "updated_at": timestamp,
                },
            )

            outcome = correlation_trace.outcome.value
            existing_incident = conn.execute(
                """
                SELECT incidents.id, incidents.ticket_id, incidents.report_path, incidents.case_status
                FROM incidents
                LEFT JOIN incident_alerts ON incident_alerts.incident_id = incidents.id
                WHERE incidents.workspace = %s
                  AND (
                    incidents.incident_key = %s
                    OR incidents.alert_id = %s
                    OR incidents.latest_alert_id = %s
                    OR incident_alerts.alert_id = %s
                  )
                ORDER BY incidents.updated_at DESC, incidents.id DESC
                LIMIT 1
                """,
                (workspace, incident_key, alert.alert_id, alert.alert_id, alert.alert_id),
            ).fetchone()
            has_report_artifacts = any(
                (
                    result.artifacts.markdown_path,
                    result.artifacts.html_path,
                    result.artifacts.pdf_path,
                    result.artifacts.markdown_content,
                )
            )
            stored_ticket_id = response.ticket_id
            stored_report_path = response.report_path
            if existing_incident is not None:
                stored_ticket_id = stored_ticket_id or existing_incident["ticket_id"]
                if not has_report_artifacts:
                    stored_report_path = stored_report_path or existing_incident["report_path"]
            stored_response = response.model_copy(
                update={"ticket_id": stored_ticket_id, "report_path": stored_report_path}
            )
            incident_params = {
                "alert_id": alert.alert_id,
                "incident_key": incident_key,
                "latest_alert_id": latest_alert_id,
                "workspace": workspace,
                "hostname": alert.hostname,
                "detection_name": alert.detection_name,
                "risk_score": enriched.risk_score,
                "risk_level": enriched.risk_level,
                "ticket_id": stored_ticket_id,
                "status": incident_status,
                "completed_at": response.completed_at,
                "report_path": stored_report_path,
                "triggered_actions": Jsonb([action.value for action in response.triggered_actions]),
                "policy_reasoning": Jsonb(response.policy_reasoning),
                "enriched_json": Jsonb(enriched.model_dump(mode="json")),
                "response_json": Jsonb(stored_response.model_dump(mode="json")),
                "timestamp": timestamp,
            }
            if existing_incident is None:
                incident_row = conn.execute(
                    """
                    INSERT INTO incidents (
                        alert_id, incident_key, latest_alert_id, workspace, hostname, detection_name,
                        risk_score, risk_level, ticket_id, status, completed_at, report_path,
                        case_status, case_owner, triggered_actions_json, policy_reasoning_json,
                        enriched_json, response_json, created_at, updated_at
                    ) VALUES (
                        %(alert_id)s, %(incident_key)s, %(latest_alert_id)s, %(workspace)s, %(hostname)s,
                        %(detection_name)s, %(risk_score)s, %(risk_level)s, %(ticket_id)s, %(status)s,
                        %(completed_at)s, %(report_path)s, 'new', NULL, %(triggered_actions)s,
                        %(policy_reasoning)s, %(enriched_json)s, %(response_json)s, %(timestamp)s, %(timestamp)s
                    )
                    RETURNING id
                    """,
                    incident_params,
                ).fetchone()
            else:
                next_case_status = existing_incident["case_status"] or IncidentCaseStatus.NEW.value
                if outcome == CorrelationOutcome.REOPENED_INCIDENT.value:
                    next_case_status = IncidentCaseStatus.IN_PROGRESS.value
                incident_row = conn.execute(
                    """
                    UPDATE incidents SET
                        latest_alert_id = %(latest_alert_id)s, hostname = %(hostname)s,
                        detection_name = %(detection_name)s, risk_score = %(risk_score)s,
                        risk_level = %(risk_level)s, ticket_id = %(ticket_id)s, status = %(status)s,
                        completed_at = %(completed_at)s, report_path = %(report_path)s,
                        case_status = %(case_status)s,
                        triggered_actions_json = %(triggered_actions)s,
                        policy_reasoning_json = %(policy_reasoning)s, enriched_json = %(enriched_json)s,
                        response_json = %(response_json)s, updated_at = %(timestamp)s
                    WHERE id = %(id)s
                    RETURNING id
                    """,
                    {**incident_params, "case_status": next_case_status, "id": existing_incident["id"]},
                ).fetchone()
            incident_id = int(incident_row["id"])

            conn.execute(
                """
                INSERT INTO incident_alerts (
                    incident_id, alert_id, linked_at, correlation_outcome,
                    correlation_strategy, correlation_fingerprint, correlation_values_json, created_at
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT (alert_id) DO UPDATE SET
                    incident_id = EXCLUDED.incident_id,
                    linked_at = EXCLUDED.linked_at,
                    correlation_outcome = EXCLUDED.correlation_outcome,
                    correlation_strategy = EXCLUDED.correlation_strategy,
                    correlation_fingerprint = EXCLUDED.correlation_fingerprint,
                    correlation_values_json = EXCLUDED.correlation_values_json,
                    created_at = EXCLUDED.created_at
                """,
                (
                    incident_id,
                    alert.alert_id,
                    alert.received_at,
                    correlation_trace.outcome.value,
                    correlation_trace.evidence[0].strategy if correlation_trace.evidence else None,
                    correlation_trace.evidence[0].fingerprint if correlation_trace.evidence else None,
                    Jsonb(correlation_trace.evidence[0].values if correlation_trace.evidence else {}),
                    timestamp,
                ),
            )

            conn.execute("DELETE FROM incident_fingerprints WHERE alert_id = %s", (alert.alert_id,))
            for fingerprint in correlation_trace.candidate_fingerprints:
                conn.execute(
                    """
                    INSERT INTO incident_fingerprints (
                        incident_id, alert_id, strategy, fingerprint, fingerprint_fields_json,
                        values_json, observed_at, created_at
                    ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                    """,
                    (
                        incident_id,
                        alert.alert_id,
                        fingerprint.strategy,
                        fingerprint.fingerprint,
                        Jsonb(list(fingerprint.fields)),
                        Jsonb(dict(fingerprint.values)),
                        alert.received_at,
                        timestamp,
                    ),
                )

            conn.execute(
                "DELETE FROM action_results WHERE incident_id = %s AND COALESCE(alert_id, '') = %s",
                (incident_id, alert.alert_id),
            )
            for action_result in response.action_results:
                serialized = action_result.model_dump(mode="json")
                conn.execute(
                    """
                    INSERT INTO action_results (
                        incident_id, alert_id, action, status, executed_at, details,
                        correlation_id, attempt_count, updated_at, raw_json, created_at
                    ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                    """,
                    (
                        incident_id,
                        alert.alert_id,
                        action_result.action.value,
                        serialized["status"],
                        action_result.executed_at,
                        action_result.details,
                        action_result.correlation_id,
                        action_result.attempt_count,
                        action_result.updated_at,
                        Jsonb(serialized),
                        timestamp,
                    ),
                )

            # Incident status reflects every alert attached to it, not just this one.
            all_statuses = conn.execute(
                "SELECT status FROM action_results WHERE incident_id = %s", (incident_id,)
            ).fetchall()
            conn.execute(
                "UPDATE incidents SET status = %s, updated_at = %s WHERE id = %s",
                (
                    self._derive_incident_status_from_payloads([{"status": row["status"]} for row in all_statuses]),
                    timestamp,
                    incident_id,
                ),
            )

            if has_report_artifacts:
                conn.execute("DELETE FROM reports WHERE incident_id = %s", (incident_id,))
                conn.execute(
                    """
                    INSERT INTO reports (
                        incident_id, markdown_path, html_path, pdf_path,
                        markdown_content, created_at, updated_at
                    ) VALUES (%s, %s, %s, %s, %s, %s, %s)
                    """,
                    (
                        incident_id,
                        self._path_to_str(result.artifacts.markdown_path),
                        self._path_to_str(result.artifacts.html_path),
                        self._path_to_str(result.artifacts.pdf_path),
                        result.artifacts.markdown_content,
                        timestamp,
                        timestamp,
                    ),
                )

            has_audit = conn.execute(
                "SELECT 1 FROM audit_events WHERE incident_id = %s LIMIT 1", (incident_id,)
            ).fetchone() is not None
            if existing_incident is None or not has_audit:
                self._append_audit_event(
                    conn,
                    incident_id=incident_id,
                    alert_id=alert.alert_id,
                    category="correlation.new_incident",
                    actor="soar-workflow",
                    message=(
                        f"New incident created for host '{alert.hostname}' with risk "
                        f"{enriched.risk_level} ({enriched.risk_score:.1f})."
                    ),
                    payload={
                        "risk_level": enriched.risk_level,
                        "risk_score": enriched.risk_score,
                        "ticket_id": stored_ticket_id,
                        "incident_key": incident_key,
                    },
                )
            elif outcome in {
                CorrelationOutcome.ATTACHED_TO_EXISTING.value,
                CorrelationOutcome.REOPENED_INCIDENT.value,
            }:
                self._append_audit_event(
                    conn,
                    incident_id=incident_id,
                    alert_id=alert.alert_id,
                    category=f"correlation.{outcome}",
                    actor="soar-workflow",
                    message=(
                        f"Alert '{alert.alert_id}' correlated into incident '{incident_key}' "
                        f"using window {correlation_trace.window}."
                    ),
                    payload=correlation_trace.model_dump(mode="json"),
                )
            for action_result in response.action_results:
                self._append_audit_event(
                    conn,
                    incident_id=incident_id,
                    alert_id=alert.alert_id,
                    category=f"action.{self._normalize_action_status(action_result.status)}",
                    actor="policy-engine",
                    message=f"Action '{action_result.action.value}' recorded as '{action_result.status}'.",
                    payload=action_result.model_dump(mode="json"),
                )

        return incident_id

    def enqueue_action_job(
        self,
        request: QueuedActionRequest,
        *,
        available_at: datetime,
        max_attempts: int,
    ) -> None:
        alert_id = str(request.payload.get("alert_id") or "")
        if not alert_id:
            raise ValueError("Queued action payload must include alert_id.")

        timestamp = self._utc_now()
        # Approval-gated actions must not be claimable by the worker until an analyst approves them.
        queue_status = (
            "waiting_approval"
            if request.requires_approval and request.approval_state != ActionApprovalState.APPROVED
            else "queued"
        )
        with self._db.connect() as conn:
            conn.execute(
                """
                INSERT INTO queue_jobs (
                    alert_id, action, queue_name, correlation_id, deduplication_key,
                    request_json, payload_json, status, available_at, locked_at,
                    worker_id, attempt_count, max_attempts, requires_approval,
                    approval_state, approval_reason, approved_by, approved_at,
                    approval_due_at, approval_escalates_at, escalation_targets_json,
                    approval_escalated_at, approval_comment, rollback_requested_by,
                    rollback_requested_at, last_error, dead_lettered_at, created_at, updated_at
                ) VALUES (
                    %s, %s, %s, %s, %s, %s, %s, %s, %s, NULL, NULL, 0, %s, %s, %s, %s, %s, %s,
                    %s, %s, %s, %s, %s, %s, %s, NULL, NULL, %s, %s
                )
                ON CONFLICT (correlation_id) DO NOTHING
                """,
                (
                    alert_id,
                    request.action.value,
                    request.queue_name,
                    request.correlation_id,
                    request.deduplication_key,
                    Jsonb(request.model_dump(mode="json")),
                    Jsonb(request.payload),
                    queue_status,
                    available_at,
                    max_attempts,
                    request.requires_approval,
                    request.approval_state.value,
                    request.approval_reason,
                    request.approved_by,
                    request.approved_at,
                    request.approval_due_at,
                    request.approval_escalates_at,
                    Jsonb(list(request.escalation_targets)),
                    request.approval_escalated_at,
                    request.approval_comment,
                    request.rollback_requested_by,
                    request.rollback_requested_at,
                    timestamp,
                    timestamp,
                ),
            )

    def claim_next_action_job(
        self,
        *,
        worker_id: str,
        queue_name: Optional[str] = None,
    ) -> Optional[dict[str, Any]]:
        timestamp = self._utc_now()
        with self._db.connect() as conn:
            if queue_name:
                row = conn.execute(
                    """
                    SELECT *
                    FROM queue_jobs
                    WHERE status IN ('queued', 'retry_pending')
                      AND queue_name = %s
                      AND available_at <= %s
                    ORDER BY available_at ASC, id ASC
                    FOR UPDATE SKIP LOCKED
                    LIMIT 1
                    """,
                    (queue_name, timestamp),
                ).fetchone()
            else:
                row = conn.execute(
                    """
                    SELECT *
                    FROM queue_jobs
                    WHERE status IN ('queued', 'retry_pending')
                      AND available_at <= %s
                    ORDER BY available_at ASC, id ASC
                    FOR UPDATE SKIP LOCKED
                    LIMIT 1
                    """,
                    (timestamp,),
                ).fetchone()
            if row is None:
                return None

            next_attempt = int(row["attempt_count"]) + 1
            conn.execute(
                """
                UPDATE queue_jobs
                SET status = 'running',
                    locked_at = %s,
                    worker_id = %s,
                    attempt_count = %s,
                    updated_at = %s
                WHERE id = %s
                """,
                (
                    timestamp,
                    worker_id,
                    next_attempt,
                    timestamp,
                    row["id"],
                ),
            )
            updated = conn.execute(
                "SELECT * FROM queue_jobs WHERE id = %s",
                (row["id"],),
            ).fetchone()
            request = QueuedActionRequest.model_validate(self._as_json_payload(row["request_json"]))
            self._upsert_action_result_for_alert(
                conn,
                row["alert_id"],
                ActionResult(
                    action=ResponseAction(request.action),
                    status="running",
                    executed_at=utc_now(),
                    details=(
                        f"Worker '{worker_id}' started '{request.action.value}' "
                        f"from queue '{row['queue_name']}'."
                    ),
                    correlation_id=row["correlation_id"],
                    attempt_count=next_attempt,
                    updated_at=utc_now(),
                ),
            )
            return dict(updated) if updated is not None else None

