from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import TYPE_CHECKING, Any, Optional, Protocol

from psycopg.types.json import Jsonb

from storage.postgres import PostgresDatabase, is_postgres_target, resolve_database_url
from storage.sqlite_repository import SQLiteIncidentRepository

if TYPE_CHECKING:
    from services.workflow_service import WorkflowResult

MAX_INCIDENT_LIST_LIMIT = 200

_INCIDENT_SCHEMA = (
    """
    CREATE TABLE IF NOT EXISTS alerts (
        alert_id TEXT PRIMARY KEY,
        hostname TEXT NOT NULL,
        username TEXT NOT NULL,
        process_name TEXT NOT NULL,
        file_path TEXT NOT NULL,
        file_hash TEXT NOT NULL,
        parent_process TEXT NOT NULL,
        command_line TEXT NOT NULL,
        destination_ip TEXT NOT NULL,
        severity TEXT NOT NULL,
        detection_name TEXT NOT NULL,
        received_at TIMESTAMPTZ NOT NULL,
        raw_json JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS incidents (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        alert_id TEXT NOT NULL UNIQUE REFERENCES alerts(alert_id) ON DELETE CASCADE,
        hostname TEXT NOT NULL,
        detection_name TEXT NOT NULL,
        risk_score DOUBLE PRECISION NOT NULL,
        risk_level TEXT NOT NULL,
        ticket_id TEXT,
        status TEXT NOT NULL,
        completed_at TIMESTAMPTZ NOT NULL,
        report_path TEXT,
        triggered_actions_json JSONB NOT NULL,
        policy_reasoning_json JSONB NOT NULL,
        enriched_json JSONB NOT NULL,
        response_json JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS action_results (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        incident_id BIGINT NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
        action TEXT NOT NULL,
        status TEXT NOT NULL,
        executed_at TIMESTAMPTZ NOT NULL,
        details TEXT NOT NULL,
        raw_json JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS reports (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        incident_id BIGINT NOT NULL UNIQUE REFERENCES incidents(id) ON DELETE CASCADE,
        markdown_path TEXT,
        html_path TEXT,
        pdf_path TEXT,
        markdown_content TEXT,
        created_at TIMESTAMPTZ NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_incidents_ticket_id ON incidents(ticket_id)",
    "CREATE INDEX IF NOT EXISTS idx_incidents_completed_at ON incidents(completed_at DESC)",
    "CREATE INDEX IF NOT EXISTS idx_incidents_risk_level ON incidents(risk_level)",
)


class IncidentRepositoryProtocol(Protocol):
    db_path: Any

    def save_workflow_result(self, result: "WorkflowResult") -> int: ...
    def get_incident_by_alert_id(self, alert_id: str) -> Optional[dict[str, Any]]: ...
    def get_incident_by_ticket_id(self, ticket_id: str) -> Optional[dict[str, Any]]: ...
    def list_incidents(
        self,
        limit: int = 100,
        *,
        status: Optional[str] = None,
        risk_level: Optional[str] = None,
        hostname: Optional[str] = None,
        ticket_id: Optional[str] = None,
    ) -> list[dict[str, Any]]: ...
    def get_incident_metrics(self) -> dict[str, Any]: ...


class SupabaseIncidentRepository:
    """Supabase/Postgres-backed persistence for workflow executions."""

    def __init__(self, db_url: Optional[str | Path] = None) -> None:
        self.db_url = resolve_database_url(db_url, preferred_env="SOAR_DATABASE_URL")
        self.db_path = self.db_url
        self._db = PostgresDatabase(self.db_url, _INCIDENT_SCHEMA)

    def save_workflow_result(self, result: "WorkflowResult") -> int:
        alert = result.alert
        enriched = result.enriched_alert
        response = result.response
        timestamp = self._utc_now()

        with self._db.connect() as conn:
            conn.execute(
                """
                INSERT INTO alerts (
                    alert_id, hostname, username, process_name, file_path, file_hash,
                    parent_process, command_line, destination_ip, severity,
                    detection_name, received_at, raw_json, created_at, updated_at
                ) VALUES (
                    %(alert_id)s, %(hostname)s, %(username)s, %(process_name)s, %(file_path)s, %(file_hash)s,
                    %(parent_process)s, %(command_line)s, %(destination_ip)s, %(severity)s,
                    %(detection_name)s, %(received_at)s, %(raw_json)s, %(created_at)s, %(updated_at)s
                )
                ON CONFLICT (alert_id) DO UPDATE SET
                    hostname = EXCLUDED.hostname,
                    username = EXCLUDED.username,
                    process_name = EXCLUDED.process_name,
                    file_path = EXCLUDED.file_path,
                    file_hash = EXCLUDED.file_hash,
                    parent_process = EXCLUDED.parent_process,
                    command_line = EXCLUDED.command_line,
                    destination_ip = EXCLUDED.destination_ip,
                    severity = EXCLUDED.severity,
                    detection_name = EXCLUDED.detection_name,
                    received_at = EXCLUDED.received_at,
                    raw_json = EXCLUDED.raw_json,
                    updated_at = EXCLUDED.updated_at
                """,
                {
                    "alert_id": alert.alert_id,
                    "hostname": alert.hostname,
                    "username": alert.username,
                    "process_name": alert.process_name,
                    "file_path": alert.file_path,
                    "file_hash": alert.file_hash,
                    "parent_process": alert.parent_process,
                    "command_line": alert.command_line,
                    "destination_ip": alert.destination_ip,
                    "severity": alert.severity.value,
                    "detection_name": alert.detection_name,
                    "received_at": alert.received_at,
                    "raw_json": Jsonb(alert.model_dump(mode="json")),
                    "created_at": timestamp,
                    "updated_at": timestamp,
                },
            )

            incident_row = conn.execute(
                """
                INSERT INTO incidents (
                    alert_id, hostname, detection_name, risk_score, risk_level,
                    ticket_id, status, completed_at, report_path,
                    triggered_actions_json, policy_reasoning_json, enriched_json,
                    response_json, created_at, updated_at
                ) VALUES (
                    %(alert_id)s, %(hostname)s, %(detection_name)s, %(risk_score)s, %(risk_level)s,
                    %(ticket_id)s, %(status)s, %(completed_at)s, %(report_path)s,
                    %(triggered_actions)s, %(policy_reasoning)s, %(enriched_json)s,
                    %(response_json)s, %(created_at)s, %(updated_at)s
                )
                ON CONFLICT (alert_id) DO UPDATE SET
                    hostname = EXCLUDED.hostname,
                    detection_name = EXCLUDED.detection_name,
                    risk_score = EXCLUDED.risk_score,
                    risk_level = EXCLUDED.risk_level,
                    ticket_id = EXCLUDED.ticket_id,
                    status = EXCLUDED.status,
                    completed_at = EXCLUDED.completed_at,
                    report_path = EXCLUDED.report_path,
                    triggered_actions_json = EXCLUDED.triggered_actions_json,
                    policy_reasoning_json = EXCLUDED.policy_reasoning_json,
                    enriched_json = EXCLUDED.enriched_json,
                    response_json = EXCLUDED.response_json,
                    updated_at = EXCLUDED.updated_at
                RETURNING id
                """,
                {
                    "alert_id": alert.alert_id,
                    "hostname": alert.hostname,
                    "detection_name": alert.detection_name,
                    "risk_score": enriched.risk_score,
                    "risk_level": enriched.risk_level,
                    "ticket_id": response.ticket_id,
                    "status": "completed",
                    "completed_at": response.completed_at,
                    "report_path": response.report_path,
                    "triggered_actions": Jsonb(
                        [action.value for action in response.triggered_actions]
                    ),
                    "policy_reasoning": Jsonb(response.policy_reasoning),
                    "enriched_json": Jsonb(enriched.model_dump(mode="json")),
                    "response_json": Jsonb(response.model_dump(mode="json")),
                    "created_at": timestamp,
                    "updated_at": timestamp,
                },
            ).fetchone()
            incident_id = int(incident_row["id"])

            conn.execute(
                "DELETE FROM action_results WHERE incident_id = %s",
                (incident_id,),
            )
            for action_result in response.action_results:
                conn.execute(
                    """
                    INSERT INTO action_results (
                        incident_id, action, status, executed_at, details, raw_json, created_at
                    ) VALUES (%s, %s, %s, %s, %s, %s, %s)
                    """,
                    (
                        incident_id,
                        action_result.action.value,
                        action_result.status,
                        action_result.executed_at,
                        action_result.details,
                        Jsonb(action_result.model_dump(mode="json")),
                        timestamp,
                    ),
                )

            conn.execute(
                "DELETE FROM reports WHERE incident_id = %s",
                (incident_id,),
            )
            if any(
                (
                    result.artifacts.markdown_path,
                    result.artifacts.html_path,
                    result.artifacts.pdf_path,
                    result.artifacts.markdown_content,
                )
            ):
                conn.execute(
                    """
                    INSERT INTO reports (
                        incident_id, markdown_path, html_path, pdf_path,
                        markdown_content, created_at, updated_at
                    ) VALUES (%s, %s, %s, %s, %s, %s, %s)
                    """,
                    (
                        incident_id,
                        self._path_to_str(result.artifacts.markdown_path),
                        self._path_to_str(result.artifacts.html_path),
                        self._path_to_str(result.artifacts.pdf_path),
                        result.artifacts.markdown_content,
                        timestamp,
                        timestamp,
                    ),
                )

        return incident_id

    def get_incident_by_alert_id(self, alert_id: str) -> Optional[dict[str, Any]]:
        return self._get_incident(
            "WHERE incidents.alert_id = %s",
            (alert_id,),
        )

    def get_incident_by_ticket_id(self, ticket_id: str) -> Optional[dict[str, Any]]:
        return self._get_incident(
            "WHERE incidents.ticket_id = %s",
            (ticket_id,),
        )

    def _get_incident(
        self,
        where_clause: str,
        params: tuple[Any, ...],
    ) -> Optional[dict[str, Any]]:
        with self._db.connect() as conn:
            row = conn.execute(
                f"""
                SELECT
                    incidents.id,
                    incidents.alert_id,
                    incidents.hostname,
                    incidents.detection_name,
                    incidents.risk_score,
                    incidents.risk_level,
                    incidents.ticket_id,
                    incidents.status,
                    incidents.completed_at,
                    incidents.report_path,
                    incidents.triggered_actions_json,
                    incidents.policy_reasoning_json,
                    incidents.enriched_json,
                    incidents.response_json,
                    incidents.created_at,
                    incidents.updated_at,
                    alerts.raw_json AS alert_json,
                    reports.markdown_path,
                    reports.html_path,
                    reports.pdf_path,
                    reports.markdown_content
                FROM incidents
                JOIN alerts ON alerts.alert_id = incidents.alert_id
                LEFT JOIN reports ON reports.incident_id = incidents.id
                {where_clause}
                ORDER BY incidents.id DESC
                LIMIT 1
                """,
                params,
            ).fetchone()
            if row is None:
                return None
            return self._deserialize_incident(conn, row)

    def list_incidents(
        self,
        limit: int = 100,
        *,
        status: Optional[str] = None,
        risk_level: Optional[str] = None,
        hostname: Optional[str] = None,
        ticket_id: Optional[str] = None,
    ) -> list[dict[str, Any]]:
        if limit < 1 or limit > MAX_INCIDENT_LIST_LIMIT:
            raise ValueError(
                f"limit must be between 1 and {MAX_INCIDENT_LIST_LIMIT} inclusive"
            )

        where_clauses: list[str] = []
        params: list[Any] = []

        if status is not None:
            where_clauses.append("status = %s")
            params.append(status)
        if risk_level is not None:
            where_clauses.append("risk_level = %s")
            params.append(risk_level)
        if hostname is not None:
            where_clauses.append("hostname = %s")
            params.append(hostname)
        if ticket_id is not None:
            where_clauses.append("ticket_id = %s")
            params.append(ticket_id)

        where_sql = ""
        if where_clauses:
            where_sql = "WHERE " + " AND ".join(where_clauses)

        with self._db.connect() as conn:
            rows = conn.execute(
                f"""
                SELECT
                    id, alert_id, hostname, detection_name, risk_score,
                    risk_level, ticket_id, status, completed_at, report_path
                FROM incidents
                {where_sql}
                ORDER BY id DESC
                LIMIT %s
                """,
                (*params, limit),
            ).fetchall()
            return [self._serialize_record(dict(row)) for row in rows]

    def get_incident_metrics(self) -> dict[str, Any]:
        with self._db.connect() as conn:
            row = conn.execute(
                """
                SELECT
                    COUNT(*) AS total_incidents,
                    COALESCE(AVG(risk_score), 0) AS average_risk_score,
                    SUM(CASE WHEN risk_level = 'critical' THEN 1 ELSE 0 END) AS critical_incidents,
                    SUM(CASE WHEN risk_level = 'high' THEN 1 ELSE 0 END) AS high_incidents,
                    SUM(CASE WHEN risk_level = 'medium' THEN 1 ELSE 0 END) AS medium_incidents,
                    SUM(CASE WHEN risk_level = 'low' THEN 1 ELSE 0 END) AS low_incidents,
                    SUM(CASE WHEN ticket_id IS NOT NULL AND ticket_id != '' THEN 1 ELSE 0 END) AS ticketed_incidents,
                    MAX(completed_at) AS latest_completed_at
                FROM incidents
                """
            ).fetchone()
        return self._serialize_record(dict(row))

    def _deserialize_incident(
        self,
        conn: Any,
        row: dict[str, Any],
    ) -> dict[str, Any]:
        result = self._serialize_record(dict(row))
        result["triggered_actions"] = self._as_json_payload(
            result.pop("triggered_actions_json")
        )
        result["policy_reasoning"] = self._as_json_payload(
            result.pop("policy_reasoning_json")
        )
        result["alert"] = self._as_json_payload(result.pop("alert_json"))
        result["enriched_alert"] = self._as_json_payload(result.pop("enriched_json"))
        result["response"] = self._as_json_payload(result.pop("response_json"))
        result["action_results"] = [
            self._serialize_record(dict(action_row))
            for action_row in conn.execute(
                """
                SELECT action, status, executed_at, details
                FROM action_results
                WHERE incident_id = %s
                ORDER BY id ASC
                """,
                (result["id"],),
            ).fetchall()
        ]
        result["report"] = {
            "markdown_path": result["markdown_path"],
            "html_path": result["html_path"],
            "pdf_path": result["pdf_path"],
            "markdown_content": result["markdown_content"],
        }
        return result

    @staticmethod
    def _as_json_payload(value: Any) -> Any:
        if value is None:
            return None
        if isinstance(value, (dict, list)):
            return value
        return json.loads(value)

    @staticmethod
    def _serialize_record(record: dict[str, Any]) -> dict[str, Any]:
        serialized: dict[str, Any] = {}
        for key, value in record.items():
            if isinstance(value, datetime):
                serialized[key] = value.astimezone(UTC).isoformat()
            else:
                serialized[key] = value
        return serialized

    @staticmethod
    def _path_to_str(path: Optional[Path]) -> Optional[str]:
        return str(path) if path is not None else None

    @staticmethod
    def _utc_now() -> datetime:
        return datetime.now(UTC)


def create_incident_repository(
    db_target: Optional[str | Path] = None,
) -> IncidentRepositoryProtocol:
    if is_postgres_target(db_target):
        return SupabaseIncidentRepository(db_target)
    if db_target is None:
        return SupabaseIncidentRepository()
    return SQLiteIncidentRepository(db_path=Path(db_target))
