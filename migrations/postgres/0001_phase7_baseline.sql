CREATE TABLE IF NOT EXISTS alerts (
    alert_id TEXT PRIMARY KEY,
    hostname TEXT NOT NULL,
    username TEXT NOT NULL,
    process_name TEXT NOT NULL,
    file_path TEXT NOT NULL,
    file_hash TEXT NOT NULL,
    parent_process TEXT NOT NULL,
    command_line TEXT NOT NULL,
    destination_ip TEXT NOT NULL,
    severity TEXT NOT NULL,
    detection_name TEXT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    raw_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id TEXT NOT NULL UNIQUE REFERENCES alerts(alert_id) ON DELETE CASCADE,
    incident_key TEXT,
    latest_alert_id TEXT,
    hostname TEXT NOT NULL,
    detection_name TEXT NOT NULL,
    risk_score DOUBLE PRECISION NOT NULL,
    risk_level TEXT NOT NULL,
    ticket_id TEXT,
    status TEXT NOT NULL,
    completed_at TIMESTAMPTZ NOT NULL,
    report_path TEXT,
    case_status TEXT NOT NULL DEFAULT 'new',
    case_owner TEXT,
    triggered_actions_json JSONB NOT NULL,
    policy_reasoning_json JSONB NOT NULL,
    enriched_json JSONB NOT NULL,
    response_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

ALTER TABLE incidents ADD COLUMN IF NOT EXISTS incident_key TEXT;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS latest_alert_id TEXT;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS case_status TEXT NOT NULL DEFAULT 'new';
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS case_owner TEXT;

CREATE TABLE IF NOT EXISTS incident_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    alert_id TEXT NOT NULL UNIQUE REFERENCES alerts(alert_id) ON DELETE CASCADE,
    linked_at TIMESTAMPTZ NOT NULL,
    correlation_outcome TEXT NOT NULL,
    correlation_strategy TEXT,
    correlation_fingerprint TEXT,
    correlation_values_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS incident_fingerprints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    alert_id TEXT NOT NULL REFERENCES alerts(alert_id) ON DELETE CASCADE,
    strategy TEXT NOT NULL,
    fingerprint TEXT NOT NULL,
    fingerprint_fields_json JSONB NOT NULL,
    values_json JSONB NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS action_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    alert_id TEXT,
    action TEXT NOT NULL,
    status TEXT NOT NULL,
    executed_at TIMESTAMPTZ NOT NULL,
    details TEXT NOT NULL,
    correlation_id TEXT,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    raw_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

ALTER TABLE action_results ADD COLUMN IF NOT EXISTS alert_id TEXT;
ALTER TABLE action_results ADD COLUMN IF NOT EXISTS correlation_id TEXT;
ALTER TABLE action_results ADD COLUMN IF NOT EXISTS attempt_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE action_results ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

CREATE TABLE IF NOT EXISTS reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL UNIQUE REFERENCES incidents(id) ON DELETE CASCADE,
    markdown_path TEXT,
    html_path TEXT,
    pdf_path TEXT,
    markdown_content TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS queue_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id TEXT NOT NULL REFERENCES alerts(alert_id) ON DELETE CASCADE,
    action TEXT NOT NULL,
    queue_name TEXT NOT NULL,
    correlation_id TEXT NOT NULL UNIQUE,
    deduplication_key TEXT NOT NULL,
    request_json JSONB NOT NULL,
    payload_json JSONB NOT NULL,
    status TEXT NOT NULL,
    available_at TIMESTAMPTZ NOT NULL,
    locked_at TIMESTAMPTZ,
    worker_id TEXT,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL DEFAULT 3,
    requires_approval BOOLEAN NOT NULL DEFAULT FALSE,
    approval_state TEXT NOT NULL DEFAULT 'not_required',
    approval_reason TEXT,
    approved_by TEXT,
    approved_at TIMESTAMPTZ,
    approval_due_at TIMESTAMPTZ,
    approval_escalates_at TIMESTAMPTZ,
    escalation_targets_json JSONB,
    approval_escalated_at TIMESTAMPTZ,
    approval_comment TEXT,
    rollback_requested_by TEXT,
    rollback_requested_at TIMESTAMPTZ,
    last_error TEXT,
    dead_lettered_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS requires_approval BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS approval_state TEXT NOT NULL DEFAULT 'not_required';
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS approval_reason TEXT;
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS approved_by TEXT;
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS approved_at TIMESTAMPTZ;
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS approval_due_at TIMESTAMPTZ;
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS approval_escalates_at TIMESTAMPTZ;
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS escalation_targets_json JSONB;
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS approval_escalated_at TIMESTAMPTZ;
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS approval_comment TEXT;
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS rollback_requested_by TEXT;
ALTER TABLE queue_jobs ADD COLUMN IF NOT EXISTS rollback_requested_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS case_notes (
    note_id TEXT PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    alert_id TEXT NOT NULL REFERENCES alerts(alert_id) ON DELETE CASCADE,
    author TEXT NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_events (
    event_id TEXT PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    alert_id TEXT NOT NULL REFERENCES alerts(alert_id) ON DELETE CASCADE,
    category TEXT NOT NULL,
    actor TEXT NOT NULL,
    message TEXT NOT NULL,
    payload_json JSONB NOT NULL,
    previous_event_hash TEXT,
    event_hash TEXT,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS saved_filters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    filters_json JSONB NOT NULL,
    created_by TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_incidents_incident_key ON incidents(incident_key);
CREATE INDEX IF NOT EXISTS idx_incidents_ticket_id ON incidents(ticket_id);
CREATE INDEX IF NOT EXISTS idx_incidents_case_status ON incidents(case_status);
CREATE INDEX IF NOT EXISTS idx_incidents_latest_alert_id ON incidents(latest_alert_id);
CREATE INDEX IF NOT EXISTS idx_incidents_completed_at ON incidents(completed_at DESC);
CREATE INDEX IF NOT EXISTS idx_incidents_risk_level ON incidents(risk_level);
CREATE INDEX IF NOT EXISTS idx_incident_alerts_incident ON incident_alerts(incident_id, linked_at DESC);
CREATE INDEX IF NOT EXISTS idx_incident_fingerprints_lookup ON incident_fingerprints(fingerprint, observed_at DESC);
CREATE INDEX IF NOT EXISTS idx_action_results_incident_action ON action_results(incident_id, alert_id, action);
CREATE INDEX IF NOT EXISTS idx_action_results_correlation ON action_results(correlation_id);
CREATE INDEX IF NOT EXISTS idx_queue_jobs_available ON queue_jobs(status, queue_name, available_at);
CREATE INDEX IF NOT EXISTS idx_case_notes_alert_id ON case_notes(alert_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_events_alert_id ON audit_events(alert_id, created_at DESC);
